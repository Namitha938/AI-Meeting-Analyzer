class GoogleCalendarService:
    """
    Step 12: Google Calendar API Integration.
    Syncs meeting tasks and creates calendar events with deep links.
    """
    @classmethod
    def generate_calendar_link(
        cls,
        title: str,
        description: str,
        deadline_str: str,
        meeting_title: str
    ) -> str:
        """
        Generates Google Calendar 1-click QuickAdd URL.
        Allows instant calendar event creation without requiring server OAuth token consent.
        """
        now = datetime.datetime.utcnow()
        # Parse approximate date
        event_date = now + datetime.timedelta(days=2)
        lower = deadline_str.lower()
        if "today" in lower:
            event_date = now
        elif "tomorrow" in lower:
            event_date = now + datetime.timedelta(days=1)
        elif "friday" in lower:
            days_ahead = (4 - now.weekday()) % 7 or 7
            event_date = now + datetime.timedelta(days=days_ahead)
        elif "monday" in lower:
            days_ahead = (0 - now.weekday()) % 7 or 7
            event_date = now + datetime.timedelta(days=days_ahead)

        start_iso = event_date.strftime("%Y%m%dT090000Z")
        end_iso = event_date.strftime("%Y%m%dT100000Z")

        details = f"{description}\n\nSource Meeting: {meeting_title}\nGenerated by Meetora AI Meeting Analyzer"
        params = {
            "action": "TEMPLATE",
            "text": f"📋 [Meetora Task] {title}",
            "details": details,
            "dates": f"{start_iso}/{end_iso}",
        }
        return f"https://calendar.google.com/calendar/render?{urllib.parse.urlencode(params)}"

    @classmethod
    def sync_action_item_to_calendar(cls, item: ActionItem, meeting: Meeting) -> Dict[str, Any]:
        """
        Syncs an ActionItem to Google Calendar.
        """
        cal_url = cls.generate_calendar_link(
            title=item.title,
            description=f"Task Owner: {item.assignee or 'Unassigned'} | Deadline: {item.deadline} | Priority: {item.priority.upper()}",
            deadline_str=item.deadline or "Tomorrow",
            meeting_title=meeting.title
        )

        event_id = f"meetora_task_{item.id}_{int(datetime.datetime.utcnow().timestamp())}"

        logger.info(f"Generated Google Calendar sync event {event_id} for ActionItem #{item.id}")

        return {
            "status": "synced",
            "event_id": event_id,
            "item_id": item.id,
            "title": item.title,
            "assignee": item.assignee,
            "deadline": item.deadline,
            "google_calendar_url": cal_url,
            "synced_at": datetime.datetime.utcnow().isoformat()
        }

    @classmethod
    def get_upcoming_schedule(cls, user_id: int, db: Any) -> List[Dict[str, Any]]:
        """
        Aggregates upcoming meeting deadlines into a structured calendar events list.
        """
        tasks = (
            db.query(ActionItem, Meeting)
            .join(Meeting, Meeting.id == ActionItem.meeting_id)
            .filter(Meeting.user_id == user_id)
            .filter(ActionItem.status != "completed")
            .all()
        )

        events = []
        now = datetime.datetime.utcnow()

        for a, m in tasks:
            cal_url = cls.generate_calendar_link(
                title=a.title,
                description=f"Meeting: {m.title} | Priority: {a.priority}",
                deadline_str=a.deadline or "Friday",
                meeting_title=m.title
            )
            events.append({
                "id": a.id,
                "title": a.title,
                "meeting_id": m.id,
                "meeting_title": m.title,
                "assignee": a.assignee or "Unassigned",
                "deadline": a.deadline or "Pending",
                "priority": a.priority,
                "status": a.status,
                "google_calendar_url": cal_url,
            })

        return events


class EmailReminderService:
    """
    Step 12: Scheduled Deadline Reminders by Email using Celery Beat.
    Sends automated reminder emails for upcoming action-item deadlines.
    """
    @classmethod
    def send_deadline_email(
        cls,
        to_email: str,
        recipient_name: str,
        tasks: List[Dict[str, Any]]
    ) -> bool:
        """
        Dispatches deadline reminder email.
        """
        subject = f"⏰ Meetora Deadline Reminder: {len(tasks)} upcoming task(s) require attention"
        
        task_bullets = "\n".join(
            f"  • {t['title']} — Due: {t['deadline']} (Priority: {t.get('priority', 'medium').upper()})"
            for t in tasks
        )

        body_text = f"""Hi {recipient_name},

This is an automated reminder from Meetora AI Meeting Analyzer.
You have {len(tasks)} upcoming action item(s) approaching their deadline:

{task_bullets}

View your meeting insights and update task progress at:
http://localhost:5173/#dashboard

Best regards,
Meetora Task Automation
"""

        if settings.SMTP_USER and settings.SMTP_PASSWORD:
            try:
                msg = MIMEMultipart()
                msg["From"] = settings.EMAILS_FROM_EMAIL
                msg["To"] = to_email
                msg["Subject"] = subject
                msg.attach(MIMEText(body_text, "plain"))

                with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT) as server:
                    server.starttls()
                    server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
                    server.send_message(msg)

                logger.info(f"Dispatched deadline reminder email to {to_email}")
                return True
            except Exception as e:
                logger.error(f"Failed to send SMTP email to {to_email}: {e}")
                return False
        else:
            # Simulated email delivery log for development
            logger.info(f"[SIMULATED EMAIL REMINDER] Sent to: {to_email} | Tasks: {len(tasks)}")
            return True

    @classmethod
    def scan_and_send_due_reminders(cls, db: Any) -> Dict[str, Any]:
        """
        Scans all pending action items and sends deadline reminders to owners.
        """
        pending_items = (
            db.query(ActionItem, Meeting, User)
            .join(Meeting, Meeting.id == ActionItem.meeting_id)
            .join(User, User.id == Meeting.user_id)
            .filter(ActionItem.status != "completed")
            .all()
        )

        grouped_by_user = {}
        for a, m, u in pending_items:
            email = u.email
            if email not in grouped_by_user:
                grouped_by_user[email] = {
                    "name": u.full_name or email.split("@")[0],
                    "tasks": []
                }
            grouped_by_user[email]["tasks"].append({
                "id": a.id,
                "title": a.title,
                "deadline": a.deadline,
                "priority": a.priority,
                "meeting_title": m.title
            })

        reminders_sent = 0
        recipients = []
        for email, data in grouped_by_user.items():
            if data["tasks"]:
                success = cls.send_deadline_email(email, data["name"], data["tasks"])
                if success:
                    reminders_sent += len(data["tasks"])
                    recipients.append(email)

        return {
            "status": "success",
            "total_reminders_dispatched": reminders_sent,
            "recipients": recipients,
            "timestamp": datetime.datetime.utcnow().isoformat()
        }
